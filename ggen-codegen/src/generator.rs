    async fn test_generate_trait_impls() {
        let config = GeneratorConfig::default();
        let generator = CodeGenerator::new(config).expect("Failed to create generator");
        let instances = Instances::new("test".to_string());

        let artifacts = generator
            .generate_trait_impls(&instances)
            .await
            .expect("Failed to generate");

        assert!(!artifacts.is_empty());
    }
